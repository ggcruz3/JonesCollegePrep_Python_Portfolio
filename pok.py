def evolve():
    global pokemon_name, pokemon_level
    if pokemon_level >= 10 and pokemon_name != "Beedrill":
        pokemon_name = "Beedrill"
        print("Congratulations Kakuna Evolved Into Beedrill!!")
        Beedrill()

    elif pokemon_level >= 7 and pokemon_name == "Weedle":
        pokemon_name = "Kakuna"
        print("Congratulations Weedle Evolved Into Kakuna ")
        Kakuna()

def train():
    global pokemon_level
    leaves = input("How many leaves does Weedle want to eat? ")
    print("Weedle ate " + leaves + " leaves!")
    pokemon_level += 1
    evolve()
def battle():
    global pokemon_level
    x = random.randint(1, 2)
    if x == 1:
        print("You lost the battle :( You just lost a level ")
        pokemon_level -= 1
    else:
        print("You won the battle! You gained two more levels")
        pokemon_level += 2
    evolve()

def info():
    print("Name: ", pokemon_name)
    print("Level: ", pokemon_level)
    print("Day: ", day)

def main():
    global day
    print("Welcome to Pokemon Game! You have been assgiened to take care of Weedle which will grow into Beedrill as you train them!")

    while True:
        print(f"Day {day} - What adventure are you choosing today? ")
        print("""
        1.Train
        2.Battle
        3.Info
        4.Quit
        """)
        choice = input("Choose an activity (1-5):")
        if choice == "1":
            train()
        elif choice == "2":
            battle()
        elif choice == "3":
            info()
        elif choice == "4":
            print("Thank You For Coming, Be Back Soon Goodbye!")
            break
        else:
            print("That is not one of the options, Please try again ")

        day += 1

#Main
